"""Compile actual LVGL9 + firmware UI with mocked services; render/test on host.

No hardware, serial port or live network access. Requires TinyCC and Pillow.
"""
import argparse
import hashlib
import io
import json
import subprocess
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_TCC = Path(r"D:\PROYECTOS\DISPOSITIVOS\ES3C28P ESP32-S3 DISPLAY\PROYECTOS\KLIPPER_ES3C28P_SOLID\output\pantallas\herramientas\tcc\tcc.exe")


def thumbnail_fixtures():
    """Real transparent PNGs exercise the production LVGL PNG decoder and scale."""
    definitions = ["/* Deterministic synthetic test PNGs, generated by render_portal_firmware.py. */"]
    for size in (100, 300):
        image = Image.new("RGBA", (size, size))
        draw = ImageDraw.Draw(image)
        def box(values):
            return tuple(round(value * size / 100) for value in values)
        draw.rounded_rectangle(box((4, 4, 96, 96)), radius=size // 12, fill="#125779", outline="#4BCFF5", width=max(2, size // 50))
        draw.polygon([box(point) for point in ((18, 30), (50, 12), (82, 30), (50, 48))], fill="#FFD740")
        draw.polygon([box(point) for point in ((18, 30), (50, 48), (50, 86), (18, 68))], fill="#E65C3C")
        draw.polygon([box(point) for point in ((50, 48), (82, 30), (82, 68), (50, 86))], fill="#26D6B0")
        stream = io.BytesIO()
        image.save(stream, format="PNG", compress_level=9)
        data = stream.getvalue()
        assert len(data) < 20000
        definitions.append(f"static const unsigned char fixture_png_{size}[] = {{" + ",".join(str(value) for value in data) + "};")
    path = ROOT / "tests/portal_host/fixtures_png.h"
    generated = ("\n".join(definitions) + "\n").encode()
    if not path.exists() or path.read_bytes() != generated:
        path.write_bytes(generated)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tcc", type=Path, default=DEFAULT_TCC)
    parser.add_argument("--output", type=Path, default=ROOT / "tests/portal_host/output")
    parser.add_argument("--skip-build", action="store_true")
    args = parser.parse_args()
    thumbnail_fixtures()
    out = args.output.resolve()
    out.mkdir(parents=True, exist_ok=True)
    exe = out / "portal_host.exe"
    lvgl = ROOT / "managed_components/lvgl__lvgl"
    ui_sources = sorted((ROOT / "components/portal_ui").glob("*.c"))
    source_files = ui_sources + [ROOT / "components/portal_assets/portal_assets.c",
                    ROOT / "tools/render_portal_firmware.py",
                    ROOT / "tests/portal_host/lv_conf.h", ROOT / "tests/portal_host/portal_host.c"]
    for component in ("portal_ui", "portal_assets", "device_network", "klipper_client", "board_jc4880"):
        source_files += sorted((ROOT / f"components/{component}").rglob("*.h"))
    source_files += sorted((ROOT / "components/audio_service/include").glob("*.h"))
    event_sources = sorted((ROOT / "components/audio_events").glob("*.c"))
    event_headers = sorted((ROOT / "components/audio_events").rglob("*.h"))
    source_files += event_sources + event_headers
    source_files += sorted((ROOT / "tests/portal_host").rglob("*.h"))
    fingerprints = {str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest() for path in source_files}
    build_manifest = out / "build_sources.json"
    if args.skip_build and (not build_manifest.exists() or json.loads(build_manifest.read_text()) != fingerprints):
        raise SystemExit("Host sources changed; rerun without --skip-build")
    if not args.skip_build:
        sources = sorted((lvgl / "src").rglob("*.c"))
        sources += [ROOT / "components/portal_assets/portal_assets.c", ROOT / "tests/portal_host/portal_host.c"] + ui_sources
        sources += event_sources
        includes = [ROOT / "tests/portal_host", lvgl, ROOT / "components/portal_ui", ROOT / "components/portal_ui/include",
                    ROOT / "components/portal_assets/include", ROOT / "components/device_network/include",
                    ROOT / "components/klipper_client/include", ROOT / "components/board_jc4880/include",
                    ROOT / "components/audio_service/include", ROOT / "components/audio_events/include"]
        options = ["-w", "-DLV_CONF_INCLUDE_SIMPLE", "-DLV_LVGL_H_INCLUDE_SIMPLE", "-DPORTAL_UI_HOST_TEST", "-o", str(exe)]
        options += ["-I" + str(path) for path in includes]
        options += list(map(str, sources))
        rsp = out / "compile.rsp"
        rsp.write_text("\n".join('"' + option.replace("\\", "/") + '"' for option in options), encoding="utf-8")
        compile_result = subprocess.run([str(args.tcc), "@" + str(rsp)], capture_output=True, text=True)
        (out / "compile.log").write_text(compile_result.stdout + compile_result.stderr, encoding="utf-8")
        if compile_result.returncode:
            raise SystemExit(compile_result.stdout + compile_result.stderr)
        if any(hashlib.sha256(path.read_bytes()).hexdigest() != fingerprints[str(path.relative_to(ROOT))] for path in source_files):
            raise SystemExit("Host sources changed during compilation; rerun")
        build_manifest.write_text(json.dumps(fingerprints, indent=2) + "\n", encoding="utf-8")
    run = subprocess.run([str(exe), str(out)], capture_output=True, text=True, encoding="utf-8", errors="replace")
    (out / "checks.log").write_text(run.stdout + run.stderr, encoding="utf-8")
    if run.returncode:
        raise SystemExit(f"Host exited {run.returncode}:\n" + run.stdout + run.stderr)
    frames = []
    captures = []
    for raw in sorted(out.glob("[0-9][0-9]_*.rgb565")):
        image = Image.frombytes("RGB", (800, 480), raw.read_bytes(), "raw", "BGR;16")
        image.save(raw.with_suffix(".png"))
        if all(low == high == 0 for low, high in image.getextrema()):
            raise SystemExit(f"Blank frame: {raw.name}")
        captures.append({"file": raw.with_suffix(".png").name, "size": list(image.size),
                         "rgb565_sha256": hashlib.sha256(raw.read_bytes()).hexdigest()})
        tile = Image.new("RGB", (400, 262), "#141a20")
        tile.paste(image.resize((400, 240)), (0, 22))
        ImageDraw.Draw(tile).text((8, 4), raw.stem, fill="white")
        frames.append(tile)
    contact = Image.new("RGB", (1200, 262 * ((len(frames) + 2) // 3)), "#141a20")
    for index, tile in enumerate(frames):
        contact.paste(tile, ((index % 3) * 400, (index // 3) * 262))
    contact.save(out / "contact_sheet.png")
    if len(frames) != 11:
        raise SystemExit(f"Expected 11 views, rendered {len(frames)}")
    report = {"renderer": "actual local LVGL 9.3 firmware UI, mocked backend, no hardware",
              "captures": captures,
              "screen_clipped_labels": [line for line in run.stdout.splitlines() if line.startswith("CLIP ")],
              "source_sha256": fingerprints}
    (out / "render_report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(next((line for line in run.stdout.splitlines() if line.startswith("SUMMARY ")), "No summary"))
    print(f"Rendered {len(frames)} actual LVGL9 frames at 800x480: {out}")


if __name__ == "__main__":
    main()
